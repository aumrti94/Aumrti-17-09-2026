// AI History Ingest — reads a patient's bag of outside medical records, page by page.
//
// A rural OPD patient arrives with hundreds of pages of old prescriptions, discharge
// summaries and lab reports. This worker transcribes every page and extracts dated clinical
// events from it. ai-history-digest then merges the result into one timeline.
//
// ── WHY THIS IS A SELF-RE-INVOKING WORKER AND NOT A PLAIN FUNCTION ──────────────────────
// 300 pages is ~20 AI calls at 10-30s each. No edge function invocation survives that. So
// the unit of work is ONE CHUNK (15 pages), the unit of scheduling is a ~90s wall budget,
// and when the budget runs out the worker re-invokes itself and returns. State lives
// entirely in patient_history_source_chunks, so a worker that dies mid-run loses at most
// one chunk — which the next invocation re-queues.
//
// ── THE COVERAGE CONTRACT ───────────────────────────────────────────────────────────────
// The feature's whole promise is "no page was missed". That is only true if a page that
// CANNOT be read still leaves a visible row. So: every page of every source gets exactly one
// chunk row, an unreadable chunk ends as status='failed' (never deleted, never skipped), and
// finalize_history_job() reports the job 'partial' rather than 'complete'. Any change here
// that makes a page disappear from the ledger breaks the only claim that matters.
//
// ── PHI HANDLING (Ananya) ───────────────────────────────────────────────────────────────
// Everything this function touches is third-party clinical PHI. NOTHING may console.log the
// request body, a storage path, a model response, or verbatim_text. The only logging is
// error NAMES and counts — same rule as ai-clarifying-questions.
//
// ── THE SERVICE-ROLE TENANT TRAP (Ananya) ───────────────────────────────────────────────
// This runs under the service role, so RLS does not protect it. EVERY read filters
// hospital_id in addition to job_id / source_id / patient_id. The hospital_id is taken from
// the JOB ROW, never from the request body — a caller who could name someone else's job_id
// must not also get to name the hospital it is checked against.
//
// Modes:
//   { job_id }                    process chunks (the normal path)
//   { job_id, retry_failed: true } re-queue failed chunks, then process
//   { sweep: true }               purge expired/stalled staging only (hourly pg_cron)

